export const findVerb = (form: string) => {
  const query = form.trim().toLocaleLowerCase('en')
  return irregularVerbs.find((entry) => [entry.base, entry.past, entry.participle, ...(entry.aliases ?? [])]
    .flatMap((value) => value.split(/\s*\/\s*/))
    .some((value) => value.toLocaleLowerCase('en') === query))
}
